export const INVITE_THEME_BY_ID = Object.fromEntries(INVITE_THEMES.map((t) => [t.id, t]))

// Theme ids from the first studio version → new theme + palette.
const LEGACY = {
  sage: ['garden', 'ivory'],
  rose: ['garden', 'blush'],
  navy: ['midnight', 'navy'],
  watercolour: ['garden', 'blush'],
}

// Resolves a theme + palette (with fallbacks), flattened for the components.
export function themeFor(themeId, paletteId) {
  const [tid, pid] = LEGACY[themeId] ?? [themeId, paletteId]
  const theme = INVITE_THEME_BY_ID[tid] ?? INVITE_THEMES[0]
  const palette = theme.palettes.find((p) => p.id === (pid ?? paletteId)) ?? theme.palettes[0]
  return { ...theme, palette, dark: Boolean(palette.dark) }
}

